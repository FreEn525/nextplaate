// Builds src/lib/worldmap.js: the world as SVG paths, one per country the site has a gallery for, one path for all the others,
// and a dot for the small countries the 1:110m map has no shape for (found on the 1:50m map).
//
//   cd <a scratch folder> && npm i world-atlas topojson-client d3-geo i18n-iso-countries
//   node <repo>/tools/build-worldmap.mjs <the scratch folder> > src/lib/worldmap.js
//
// Data: Natural Earth (public domain) through the world-atlas package (ISC). Projection: Equal Earth (d3-geo). Antarctica is left out.
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const dir = path.resolve(process.argv[2] || '.');
const require = createRequire(dir + '/');
const { feature } = require('topojson-client');
const { geoEqualEarth, geoPath, geoCentroid } = require('d3-geo');
const ic = require('i18n-iso-countries');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const codes = [...fs.readFileSync(path.join(root, 'src/lib/countries.js'), 'utf8').matchAll(/code: '([a-z]+)'/g)].map(m => m[1]);
const alias = { uk: 'gb' };                                   // the site writes uk for the United Kingdom
const load = res => feature(JSON.parse(fs.readFileSync(path.join(dir, `node_modules/world-atlas/countries-${res}.json`), 'utf8')), JSON.parse(fs.readFileSync(path.join(dir, `node_modules/world-atlas/countries-${res}.json`), 'utf8')).objects.countries).features
  .filter(f => String(f.id).padStart(3, '0') !== '010');       // no Antarctica
const alpha = f => (ic.numericToAlpha2(String(f.id).padStart(3, '0')) || '').toLowerCase();
const f110 = load('110m'), f50 = load('50m');
const W = 1000;
const projection = geoEqualEarth().fitWidth(W, { type: 'FeatureCollection', features: f110 });
const gp = geoPath(projection).digits(0);
const [[, y0], [, y1]] = gp.bounds({ type: 'FeatureCollection', features: f110 });
const H = Math.ceil(y1 - y0) + 2;
projection.translate([projection.translate()[0], projection.translate()[1] - y0 + 1]);
const mine = new Map(codes.map(c => [alias[c] || c, c]));
const shapes = {}, rest = [];
for (const f of f110) {
  const a = alpha(f), site = mine.get(a);
  const d = gp(f);
  if (!d) continue;
  if (site) shapes[site] = d; else rest.push(d);
}
const dots = {};
for (const c of codes) {
  if (shapes[c]) continue;
  const a = alias[c] || c;
  const f = f50.find(x => alpha(x) === a);
  const pt = f ? projection(geoCentroid(f)) : c === 'gi' ? projection([-5.35, 36.14]) : null;   // Gibraltar is on no country map
  if (pt) dots[c] = pt.map(v => Math.round(v * 10) / 10);
}
// a close view of Europe (most photos are there), the same shape as the whole map
const [ex0, ey0] = projection([-25, 71.5]), [ex1, ey1] = projection([48, 33.5]);
let vw = ex1 - ex0, vh = ey1 - ey0;
if (vw / vh < W / H) vw = vh * W / H; else vh = vw * H / W;                 // the ratio of the map, centred on the same middle
const vx = (ex0 + ex1) / 2 - vw / 2, vy = (ey0 + ey1) / 2 - vh / 2;
const views = { europe: [vx, vy, vw, vh].map(v => Math.round(v * 10) / 10) };
console.log(`// Generated by tools/build-worldmap.mjs from Natural Earth (public domain, through world-atlas, ISC). Do not edit by hand.
// shapes: a path per country the site has (by the site's code); rest: every other country in one path; dots: the countries too small for
// the map (at their centre); the codes with neither (su, xx) are listed by the map under it.
const WORLD_MAP = ${JSON.stringify({ w: W, h: H, views, shapes, rest: rest.join(''), dots })};`);
